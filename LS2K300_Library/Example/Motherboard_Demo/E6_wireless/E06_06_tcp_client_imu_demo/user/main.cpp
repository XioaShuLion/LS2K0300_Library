// 另外一端的IP地址
#define SERVER_IP "10.87.146.239"
// 端口号
#define PORT 8086

//-------------------------------------------------------------------------------------------------------------------
// 变量简介     TCP客户端设备对象
// 参数说明     无
// 返回参数     无
// 使用示例     tcp_client_dev.init(SERVER_IP, PORT);
// 备注信息     封装TCP客户端的初始化、收发数据等成员函数
//-------------------------------------------------------------------------------------------------------------------
zf_driver_tcp_client tcp_client_dev;

//-------------------------------------------------------------------------------------------------------------------
// 变量简介     IMU传感器设备操作对象
// 参数说明     无
// 返回参数     无
// 使用示例     imu_dev.init(); imu_dev.get_gyro_x();
// 备注信息     封装IMU初始化、数据读取、设备类型识别等接口
//-------------------------------------------------------------------------------------------------------------------
zf_device_imu imu_dev;

//-------------------------------------------------------------------------------------------------------------------
// 变量简介     PIT定时器设备对象
// 参数说明     无
// 返回参数     无
// 使用示例     pit_timer.init_ms(10, pit_callback);
// 备注信息     用于创建周期中断定时器，实现陀螺仪数据定时采集
//-------------------------------------------------------------------------------------------------------------------
zf_driver_pit pit_timer;

//-------------------------------------------------------------------------------------------------------------------
// 变量简介     陀螺仪三轴角速度原始数据缓存
// 参数说明     无
// 返回参数     无
// 使用示例     直接赋值与读取，均为int16整型原始采集值
// 备注信息     在PIT中断中更新，在主循环中读取发送
//-------------------------------------------------------------------------------------------------------------------
int16 gyro_x = 0, gyro_y = 0, gyro_z = 0;

//-------------------------------------------------------------------------------------------------------------------
// 变量简介     四元数缓存(标准顺序 w,x,y,z)
// 参数说明     无
// 返回参数     无
// 使用示例     printf("w=%f x=%f y=%f z=%f", quat_w, quat_x, quat_y, quat_z);
// 备注信息     仅IMU660RC硬件内置姿态解算，其余型号无数据(保持为0)
//-------------------------------------------------------------------------------------------------------------------
float quat_w = 0, quat_x = 0, quat_y = 0, quat_z = 0;

//-------------------------------------------------------------------------------------------------------------------
// 变量简介     欧拉角缓存(滚转 roll、俯仰 pitch、偏航 yaw，单位：度)
// 参数说明     无
// 返回参数     无
// 使用示例     printf("roll=%f pitch=%f yaw=%f", euler_roll, euler_pitch, euler_yaw);
// 备注信息     仅IMU660RC硬件内置姿态解算，其余型号无数据(保持为0)
//-------------------------------------------------------------------------------------------------------------------
float euler_roll = 0, euler_pitch = 0, euler_yaw = 0;

//-------------------------------------------------------------------------------------------------------------------
// 变量简介     TCP发送缓冲区
// 参数说明     无
// 返回参数     无
// 使用示例     snprintf(send_buf, sizeof(send_buf), ...);
// 备注信息     存放格式化后的陀螺仪/四元数/欧拉角文本数据
//-------------------------------------------------------------------------------------------------------------------
char send_buf[256];

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     PIT定时器10ms周期中断回调函数
// 参数说明     void
// 返回参数     void
// 使用示例     pit_timer.init_ms(10, pit_callback); 注册该回调函数
// 备注信息     定时器中断上下文，仅做数据读取赋值，禁止耗时操作
//-------------------------------------------------------------------------------------------------------------------
void pit_callback()
{
    // 读取三轴陀螺仪(角速度)原始数据
    gyro_x = imu_dev.get_gyro_x();
    gyro_y = imu_dev.get_gyro_y();
    gyro_z = imu_dev.get_gyro_z();

    // 仅IMU660RC硬件内置四元数姿态解算，可输出四元数与欧拉角
    if(imu_dev.imu_type == DEV_IMU660RC)
    {
        // 获取四元数寄存器数据
        imu_dev.get_quarternion();
        // 四元数归一化
        imu_dev.quarternion_normalize();
        // 四元数转欧拉角
        imu_dev.quarternion_to_euler(&euler_roll, &euler_pitch, &euler_yaw);

        // 获取归一化后的四元数(标准顺序 w,x,y,z)
        float *q = imu_dev.get_quarternion_float();
        if(q != nullptr)
        {
            quat_w = q[0];
            quat_x = q[1];
            quat_y = q[2];
            quat_z = q[3];
        }
    }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     程序入口主函数
// 参数说明     无
// 返回参数     int  -1：初始化失败；0：正常循环运行无退出
// 使用示例     上电由系统自动调用
// 备注信息     流程：IMU初始化→TCP客户端初始化→启动10ms定时采集→主循环周期性发送陀螺仪数据(660RC额外发送四元数与欧拉角)
//-------------------------------------------------------------------------------------------------------------------
int main()
{
    // IMU传感器初始化，自动检测挂载的IMU型号并完成底层配置
    if(imu_dev.init() == DEV_NO_FIND)
    {
        printf("NO FIND IMU DEV\r\n");
        return -1;
    }
    printf("IMU DEV IS %d\r\n", imu_dev.imu_type);

    // 初始化TCP客户端，连接上位机(电脑)的TCP Server
    if(tcp_client_dev.init(SERVER_IP, PORT) == 0)
    {
        printf("tcp_client ok\r\n");
    }
    else
    {
        printf("tcp_client error\r\n");
        return -1;
    }

    // 初始化PIT定时器，周期10ms，定时到执行pit_callback回调函数
    pit_timer.init_ms(10, pit_callback);

    // 主循环：周期性读取数据并通过TCP发送
    while(true)
    {
        int len = 0;

        if(imu_dev.imu_type == DEV_IMU660RC)
        {
            //  IMU660RC：发送陀螺仪
            // len = snprintf(send_buf, sizeof(send_buf),
            //                "gyro: %d,%d,%d  ,
            //                gyro_x, gyro_y, gyro_z,);

            //                            //发送四元数(w,x,y,z)
            len = snprintf(send_buf, sizeof(send_buf),
                           " %.4f,%.4f,%.4f,%.4f\r\n",
                           quat_w, quat_x, quat_y, quat_z);

             // 发送欧拉角(roll,pitch,yaw)
            // len = snprintf(send_buf, sizeof(send_buf),
            //                "%.2f,%.2f,%.2f\r\n",
            //                euler_roll, euler_pitch, euler_yaw);

        }
        else
        {
            // 其余型号：仅发送陀螺仪数据
            len = snprintf(send_buf, sizeof(send_buf),
                           "gyro: %d,%d,%d\r\n",
                           gyro_x, gyro_y, gyro_z);
        }

        // len小于0表示格式化失败，大于0时发送实际字节数
        if(len > 0)
        {
            tcp_client_dev.send_data((const uint8 *)send_buf, (uint32)len);
        }

        // 同时通过调试串口打印，方便排查
        printf("%s", send_buf);

        // 延时50ms，控制发送频率(约20Hz)，避免刷屏过快
        system_delay_ms(50);
    }

    return 0;
}

